INTENSITY_LEVELS: list[str] = ["轻微", "明显", "强烈", "非常强烈"]


def all_emotions() -> list[str]:
    """返回情绪库的完整词表（家族梯度词 + 复合 + 社会 + 中文高频）。"""
    words: list[str] = []
    for gradient in EMOTION_FAMILIES.values():
        words.extend(gradient)
    return words + COMPOUND_EMOTIONS + SOCIAL_EMOTIONS + CHINESE_COMMON_EMOTIONS


def intensity_text(score: int) -> str:
    """把 0-100 的强度分转成四级人话（轻微/明显/强烈/非常强烈）。"""
    if score < 30:
        return INTENSITY_LEVELS[0]
    if score < 60:
        return INTENSITY_LEVELS[1]
    if score < 85:
        return INTENSITY_LEVELS[2]
    return INTENSITY_LEVELS[3]


